const CITY_BY_IATA: ReadonlyMap<string, City> = new Map(CITIES.map((c) => [c.iata, c]));

/** Look up a city by IATA code, or `undefined` if it is not in the dataset. */
export function getCity(iata: string): City | undefined {
  return CITY_BY_IATA.get(iata);
}

/** Cities strong enough to route through (hubStrength >= 3). */
export const STOPOVER_HUBS: City[] = CITIES.filter((c) => c.hubStrength >= 3);
